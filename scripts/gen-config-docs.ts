/**
 * Generates docs/config-reference.md from the Zod schema.
 * Run `pnpm docs:config` after changing src/config/schema.ts; CI runs it with --check.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { z } from 'zod';
import { configSchema } from '../src/config/schema.js';

const OUTPUT = 'docs/config-reference.md';

interface JsonSchema {
  type?: string | string[];
  description?: string;
  default?: unknown;
  enum?: unknown[];
  const?: unknown;
  properties?: Record<string, JsonSchema>;
  required?: string[];
  items?: JsonSchema;
  additionalProperties?: JsonSchema | boolean;
  anyOf?: JsonSchema[];
}

interface Row {
  key: string;
  type: string;
  required: boolean;
  defaultValue: string;
  description: string;
}

const cell = (text: string): string => text.replace(/\|/g, '\\|').replace(/\n/g, ' ');

function typeOf(node: JsonSchema): string {
  if (node.enum) return node.enum.map((value) => `\`${String(value)}\``).join(' \\| ');
  if (node.anyOf) return node.anyOf.map(typeOf).join(' \\| ');
  if (node.type === 'array') return `list of ${node.items ? typeOf(node.items) : 'any'}`;
  if (node.type === 'object') {
    if (node.properties) return 'object';
    const values = node.additionalProperties;
    return `map of string to ${typeof values === 'object' ? typeOf(values) : 'any'}`;
  }
  return Array.isArray(node.type) ? node.type.join(' \\| ') : (node.type ?? 'any');
}

function defaultOf(node: JsonSchema): string {
  if (node.default === undefined) return '';
  const text = JSON.stringify(node.default);
  if (text === '{}' && node.properties) return '';
  return `\`${text.length > 60 ? `${text.slice(0, 57)}...` : text}\``;
}

function collect(node: JsonSchema, path: string, required: boolean, rows: Row[]): void {
  const isSection = node.type === 'object' && node.properties !== undefined;
  const itemSection = node.type === 'array' && node.items?.properties !== undefined;

  if (path) {
    rows.push({
      key: path,
      type: typeOf(node),
      required,
      defaultValue: isSection ? '' : defaultOf(node),
      description: node.description ?? '',
    });
  }

  const children = isSection ? node : itemSection ? node.items : undefined;
  if (!children?.properties) return;
  const prefix = itemSection ? `${path}[]` : path;
  for (const [key, child] of Object.entries(children.properties)) {
    collect(
      child,
      prefix ? `${prefix}.${key}` : key,
      children.required?.includes(key) ?? false,
      rows,
    );
  }
}

function render(): string {
  const root = z.toJSONSchema(configSchema, { io: 'input', unrepresentable: 'any' }) as JsonSchema;
  const lines: string[] = [
    '# Configuration reference',
    '',
    '<!-- Generated by `pnpm docs:config` from src/config/schema.ts. Do not edit by hand. -->',
    '',
    'All settings live in `config.yaml`; secrets live in `.env`. Unknown keys are rejected, so a typo',
    'fails at startup with the path of the offending key. Run `pnpm config:check` to validate a file',
    'without starting anything.',
    '',
  ];

  for (const [section, node] of Object.entries(root.properties ?? {})) {
    lines.push(`## \`${section}\``, '');
    if (node.description) lines.push(node.description, '');
    const rows: Row[] = [];
    collect(node, section, root.required?.includes(section) ?? false, rows);
    lines.push('| Key | Type | Default | Description |', '| --- | --- | --- | --- |');
    for (const row of rows.slice(1)) {
      const description = row.required ? `**Required.** ${row.description}` : row.description;
      lines.push(
        `| \`${row.key}\` | ${row.type} | ${cell(row.defaultValue)} | ${cell(description.trim())} |`,
      );
    }
    lines.push('');
  }

  lines.push(
    '## Environment variables',
    '',
    '| Variable | Required | Purpose |',
    '| --- | --- | --- |',
    '| `TELEGRAM_BOT_TOKEN` | bot | Token from @BotFather. |',
    '| `DATABASE_URL` | bot, worker | PostgreSQL connection string. |',
    '| `CONFIG_PATH` | no | Path to the config file. Defaults to `config.yaml`. |',
    '| `LOG_LEVEL` | no | Overrides `app.log_level`. |',
    '| `ANTHROPIC_API_KEY` | no | LLM scoring and application drafts (planned). |',
    '| `NOTION_TOKEN` | no | Notion tracker (planned). |',
    '| `TG_API_ID`, `TG_API_HASH`, `TG_SESSION` | no | Telegram channel reader (planned). |',
    '',
  );
  return lines.join('\n');
}

const next = render();
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUTPUT, 'utf8');
  } catch {
    /* missing file is reported below */
  }
  if (current !== next) {
    console.error(`${OUTPUT} is out of date. Run \`pnpm docs:config\` and commit the result.`);
    process.exit(1);
  }
  console.log(`${OUTPUT} is up to date.`);
} else {
  writeFileSync(OUTPUT, next);
  console.log(`Wrote ${OUTPUT}`);
}
